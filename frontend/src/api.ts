import { type Card, type Deck, type DeckDetail, type DeckSection, type Paginated, type SidePattern, type SidePatternPayload, type WthGuide, type WthGuideSummary, type WthPayload, type Combo, type ComboSummary, type ComboPayload, type Playlist, type PlaylistSummary, type PlaylistPayload, type StoreListing, type StoreListingDetail, type PurchasedPlaylistSummary, type PurchasedPlaylist } from './types';
import { AUTH_EXPIRED_EVENT, CSRF_HEADER_NAME, CSRF_HEADER_VALUE } from './auth/session';

/** Generic call: handles backend errors and 204 responses (no-body response). */
export async function request<T>(url: string, init?: RequestInit): Promise<T> {
    // Header needed for CSRF protection so that the backend can identify requests generated by this app
    const headers = new Headers(init?.headers);
    headers.set(CSRF_HEADER_NAME, CSRF_HEADER_VALUE);
    const res = await fetch(url, { ...init, headers, credentials: 'same-origin' });

    // 401 outside /api/auth/ means the session expired, so we notify the AuthProvider
    if (res.status === 401 && !url.startsWith('/api/auth/')) {
        window.dispatchEvent(new Event(AUTH_EXPIRED_EVENT));
    }

    if (!res.ok) {
        let message = `Server Error: ${res.status}`;
        try {
            const body = await res.json();
            // Nest returns `message` as text, or as a list (validation and rules).
            message = Array.isArray(body.message)
                ? body.message.join('\n')
                : (body.message ?? message);
        } catch {
            // the body wasn't JSON, so we keep the generic message
        }
        throw new Error(message);
    }

    if (res.status === 204) {
        return undefined as T;
    }
    return res.json();
}

export function jsonBody(method: string, data: unknown): RequestInit {
    return {
        method,
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(data),
    };
}

/** ---------------------------------------------------------- Handle Cards */

export async function searchCards(params: {
    search: string;
    page: number;
    limit: number;
}) {
    const query = new URLSearchParams({
        page: String(params.page),
        limit: String(params.limit),
    });
    if (params.search) {
        query.set('search', params.search);
    }
    return request<Paginated<Card>>(`/api/cards?${query}`);
}

// Card image address, provided by the backend
export function cardImageUrl(id: number) {
    return `/api/cards/${id}/image`;
}

/** ---------------------------------------------------------- Handle Decks */

export function listDecks() {
    return request<Deck[]>('/api/decks');
}

export function getDeck(id: string) {
    return request<DeckDetail>(`/api/decks/${id}`);
}

export function createDeck(data: { name: string, archetype?: string }) {
    return request<Deck>('/api/decks', jsonBody('POST', data));
}

export function updateDeck(id: string, data: { name?: string; archetype?: string | null }) {
    return request<DeckDetail>(`/api/decks/${id}`, jsonBody('PATCH', data));
}

export function deleteDeck(id: string) {
    return request<void>(`/api/decks/${id}`, { method: 'DELETE' });
}

/** ----------------------------------------------------------- Handle Deck */

export function saveDeckList(
    deckId: string,
    cards: { cardId: number; section: DeckSection; quantity: number }[],
) {
    return request<DeckDetail>(
        `/api/decks/${deckId}/list`,
        jsonBody('PUT', { cards })
    );
}

